// Синтетические данные существуют только в тесте, в публичные реестры не добавляются.
import assert from 'node:assert/strict';
import { validate_publications, get_published, published_routes } from '../src/data/publications.ts';
const today = '2026-10-27';
const rights = { status: 'approved', holder: 'Synthetic fixture', evidence: 'test fixture only' };
const source = { reference: 'test fixture only', approved_by: 'Synthetic reviewer', approved_on: '2026-10-20' };
const image = { src: '/media/news/test.webp', mime: 'image/webp', bytes: 123, sha256: 'a'.repeat(64), rights, alt: 'Synthetic image', width: 800, height: 500 };
const news = { slug: 'synthetic-test', status: 'approved', title: 'Synthetic test', summary: 'Synthetic summary', paragraphs: ['Synthetic content'], published_on: '2026-10-22', source, rights, image };
const document = { slug: 'synthetic-document', status: 'approved', title: 'Synthetic document', description: 'Synthetic description', published_on: '2026-10-22', valid_from: '2026-01-01', valid_until: '2027-01-01', source, rights, asset: { src: '/media/documents/test.pdf', mime: 'application/pdf', bytes: 300, sha256: 'b'.repeat(64), rights }, accessible_text: ['Synthetic text'] };
assert.deepEqual(published_routes, []);
assert.deepEqual(get_published({ news: [{ ...news, status: 'draft' }], documents: [{ ...document, status: 'draft' }] }, today).routes, []);
const input = { news: [news], documents: [document] };
assert.deepEqual(validate_publications(input, today), []);
assert.deepEqual(get_published(input, today).routes, ['/news', '/news/synthetic-test', '/documents']);
const invalid = (entry) => assert.ok(validate_publications({ news: [entry], documents: [] }, today).length > 0);
invalid({ ...news, image: { ...image, src: 'https://example.test/image.webp' } });
invalid({ ...news, image: { ...image, src: '/media/news/../secret.webp' } });
invalid({ ...news, image: { ...image, src: '//example.test/image.webp' } });
invalid({ ...news, image: { ...image, mime: 'text/html' } });
invalid({ ...news, image: { ...image, rights: { ...rights, status: 'pending' } } });
invalid({ ...news, rights: { ...rights, evidence: '' } });
invalid({ ...news, source: { ...source, reference: '' } });
invalid({ ...news, published_on: '2026-02-30' });
invalid({ ...news, published_on: '2027-01-01' });
invalid({ ...news, published_on: '2026-1-1' });
invalid({ ...news, slug: '../secret' });
invalid({ ...news, paragraphs: [] });
assert.ok(validate_publications({ news: [news, news], documents: [] }, today).length > 0);
assert.ok(validate_publications({ news: [], documents: [{ ...document, valid_until: '2026-01-02' }] }, today).length > 0);
assert.ok(validate_publications({ news: [], documents: [{ ...document, valid_from: '2027-01-02' }] }, today).length > 0);
assert.ok(validate_publications({ news: [], documents: [{ ...document, accessible_text: [] }] }, today).length > 0);
assert.throws(() => get_published({ news: [{ ...news, published_on: 'invalid' }], documents: [] }, today));
console.log('test-publications: OK — пустые реестры, drafts, источники/права, local assets, MIME/даты/сроки, дубликаты, fail closed');
